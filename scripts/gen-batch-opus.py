"""
Generate batch JSON for seeding — reads tracks from /tmp/opus_tracks.json,
generates comments from a pre-written content file, and applies to DB.
"""
import json
import random
import time
import sys
import os

PERSONAS_PATH = "/root/.openclaw/workspace/TangKinhCac/scripts/amkinh-personas-opus.json"
TRACKS_PATH = "/tmp/opus_tracks.json"
PROGRESS_PATH = "/root/.openclaw/workspace/TangKinhCac/state/seed-opus-progress.json"

def load_personas():
    with open(PERSONAS_PATH) as f:
        return json.load(f)

def random_ts_past_14_days():
    """Random timestamp 1-14 days in the past (ms)."""
    now = int(time.time() * 1000)
    offset = random.randint(1 * 86400 * 1000, 14 * 86400 * 1000)
    return now - offset

def generate_timestamps(n, base_ts=None):
    """Generate n sorted timestamps within 1-14 days past."""
    timestamps = sorted([random_ts_past_14_days() for _ in range(n)])
    return timestamps

def calc_targets(play_count):
    """Calculate like and comment targets from play count."""
    like_pct = random.uniform(0.08, 0.13)
    comment_pct = random.uniform(0.03, 0.06)
    target_likes = max(1, int(play_count * like_pct))
    target_comments = max(2, int(play_count * comment_pct))
    return target_likes, target_comments

def load_progress():
    if os.path.exists(PROGRESS_PATH):
        with open(PROGRESS_PATH) as f:
            return json.load(f)
    return {"done": 0, "total": 155, "last_tid": "", "batches_applied": []}

def save_progress(prog):
    os.makedirs(os.path.dirname(PROGRESS_PATH), exist_ok=True)
    with open(PROGRESS_PATH, 'w') as f:
        json.dump(prog, f, indent=2)

